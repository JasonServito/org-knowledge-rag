"""The ablation table (S06-T4) from hand-made run summaries.

Every expected cell is hand arithmetic over the summaries below: a value is the mean over the
row's runs to 3 decimals, then "(min–max)" when the row has more than 1 run; an AC cell is the
mean of each run's pass / total. The p95 and cost cells (S08-T3) use 1 and 4 decimals, and a run
without the value is left out. The time cells (S09-T3) and the authority-selection cell (S09-T7)
are each run's count / total, to 3 decimals like the metric cells, and a run without the value is
left out.
"""

# The table's ranges use an en dash, as the run contract pins them; ruff flags it as ambiguous.
# ruff: noqa: RUF001, RUF002

from datetime import UTC, datetime

from orgknow.eval.runner import Count, Rate, Summary
from orgknow.eval.table import ablation_table

SHA_V0 = "0123456789abcdef" * 4
SHA_DEMO = "fedcba9876543210" * 4


def _summary(
    golden_sha256: str,
    hour: int,
    questions: int,
    metrics: tuple[float, float, float, float],
    ac: tuple[tuple[int, int], tuple[int, int], tuple[int, int]],
    errors: int,
    name: str = "dense",
    p95_cost: tuple[float | None, float | None, float | None] = (None, None, None),
    time: tuple[Count | None, Rate | None, Rate | None] = (None, None, None),
    authority: Rate | None = None,
) -> Summary:
    """A summary started at `hour`:00 UTC; `metrics` is (recall, hit, mrr, ndcg), `ac` is
    (pass, total) for AC1, AC2 and AC3, `p95_cost` is (p95 latency, retrieve p95, cost per
    question), None as in a summary written before S08-T3, and `time` is (stale, temporal,
    router), None as in a summary written before S09-T3, and `authority` None as in one written
    before S09-T7. The fields the table doesn't show are filler."""
    recall, hit, mrr, ndcg = metrics
    (ac1, ac1_total), (ac2, ac2_total), (ac3, ac3_total) = ac
    latency_s_p95, retrieve_s_p95, cost_usd_mean = p95_cost
    stale, temporal, router = time
    return Summary(
        name=name,
        golden_sha256=golden_sha256,
        started_at=datetime(2026, 10, 8, hour, tzinfo=UTC),
        questions=questions,
        answerable=questions - 1,
        errors=errors,
        recall=recall,
        hit=hit,
        mrr=mrr,
        ndcg=ndcg,
        distinct_sections=7.0,
        ac1=Rate(pass_=ac1, total=ac1_total),
        ac2=Rate(pass_=ac2, total=ac2_total),
        ac3=Rate(pass_=ac3, total=ac3_total),
        false_refusals=Count(count=0, total=questions - 1),
        input_tokens=1000,
        output_tokens=300,
        latency_s_mean=12.5,
        latency_s_p95=latency_s_p95,
        retrieve_s_p95=retrieve_s_p95,
        cost_usd_mean=cost_usd_mean,
        stale=stale,
        temporal=temporal,
        router=router,
        authority=authority,
    )


# Two runs of v0 at 10:00 and 12:00, and one run of the demo set between them at 11:00.
V0_FIRST = _summary(SHA_V0, 10, 40, (0.5, 1.0, 0.25, 0.4), ((2, 3), (10, 10), (2, 4)), errors=0)
V0_SECOND = _summary(SHA_V0, 12, 40, (0.7, 0.8, 0.35, 0.5), ((1, 1), (9, 10), (3, 4)), errors=1)
# AC1 total 0: nothing was `answered`, so the rate is n/a.
DEMO = _summary(SHA_DEMO, 11, 3, (0.75, 1.0, 0.75, 0.7), ((0, 0), (1, 3), (1, 1)), errors=0)

HEADER = (
    "| Pipeline | Set | Runs | Questions | Recall@10 | Hit@10 | MRR | nDCG@10 | AC1 | AC2 | AC3 "
    "| Errors | p95 latency (s) | Retrieve p95 (s) | Cost/question ($) | Stale rate "
    "| Temporal acc. | Router acc. | Authority sel. |\n"
    "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n"
)
GENERATED = (
    "Generated by `make eval-table` from each results folder's run.json and summary.json: "
    "don't edit.\n"
)


def test_one_row_per_pipeline_and_set_in_order_of_first_run() -> None:
    # Given out of order: the demo run first, then v0's second run, then its first.
    runs = [("demo.yaml", DEMO), ("v0.yaml", V0_SECOND), ("v0.yaml", V0_FIRST)]

    table = ablation_table(runs)

    # v0: recall (0.5 + 0.7) / 2 = 0.6; hit (1.0 + 0.8) / 2 = 0.9; MRR (0.25 + 0.35) / 2 = 0.3;
    # nDCG (0.4 + 0.5) / 2 = 0.45; AC1 (2/3 + 1/1) / 2 = 0.8333, min 0.6667; AC2 (1.0 + 0.9) / 2
    # = 0.95; AC3 (2/4 + 3/4) / 2 = 0.625; errors (0 + 1) / 2 = 0.5.
    # demo: one run, so no range; AC1 n/a; AC2 1/3 = 0.3333.
    assert table == (
        GENERATED + "\n" + HEADER + "| dense | v0.yaml 01234567 | 2 | 40 "
        "| 0.600 (0.500–0.700) | 0.900 (0.800–1.000) | 0.300 (0.250–0.350) "
        "| 0.450 (0.400–0.500) | 0.833 (0.667–1.000) | 0.950 (0.900–1.000) "
        "| 0.625 (0.500–0.750) | 0.500 (0.000–1.000) | n/a | n/a | n/a | n/a | n/a | n/a "
        "| n/a |\n"
        "| dense | demo.yaml fedcba98 | 1 | 3 | 0.750 | 1.000 | 0.750 | 0.700 | n/a | 0.333 "
        "| 1.000 | 0.000 | n/a | n/a | n/a | n/a | n/a | n/a | n/a |\n"
    )


def test_another_pipeline_name_is_another_row() -> None:
    hybrid = _summary(SHA_V0, 13, 40, (0.9, 1.0, 0.5, 0.6), ((3, 3), (3, 3), (4, 4)), 0, "hybrid")

    lines = ablation_table([("v0.yaml", V0_FIRST), ("v0.yaml", hybrid)]).splitlines()

    assert lines[4:] == [
        "| dense | v0.yaml 01234567 | 1 | 40 | 0.500 | 1.000 | 0.250 | 0.400 | 0.667 | 1.000 "
        "| 0.500 | 0.000 | n/a | n/a | n/a | n/a | n/a | n/a | n/a |",
        "| hybrid | v0.yaml 01234567 | 1 | 40 | 0.900 | 1.000 | 0.500 | 0.600 | 1.000 | 1.000 "
        "| 1.000 | 0.000 | n/a | n/a | n/a | n/a | n/a | n/a | n/a |",
    ]


def test_runs_of_one_row_with_different_question_counts_show_each_count() -> None:
    # A smoke run and a full run of one set share a row (one row per name and set): the
    # Questions cell shows both counts, so the mix is visible.
    smoke = _summary(SHA_V0, 9, 12, (0.5, 1.0, 0.25, 0.4), ((2, 3), (10, 10), (2, 4)), 0)

    row = ablation_table([("v0.yaml", smoke), ("v0.yaml", V0_FIRST)]).splitlines()[4]

    assert row.startswith("| dense | v0.yaml 01234567 | 2 | 12, 40 | ")


def test_p95_and_cost_cells_leave_out_a_run_without_the_value() -> None:
    # S08-T3. Three runs of one row: the first written before S08-T3 (no p95 or cost), the
    # second before the retrieve stage was timed (no retrieve p95).
    old = _summary(SHA_V0, 9, 40, (0.5, 1.0, 0.25, 0.4), ((2, 3), (10, 10), (2, 4)), 0)
    second = _summary(
        SHA_V0, 10, 40, (0.5, 1.0, 0.25, 0.4), ((2, 3), (10, 10), (2, 4)), 0,
        p95_cost=(10.0, None, 0.02),
    )  # fmt: skip
    third = _summary(
        SHA_V0, 11, 40, (0.5, 1.0, 0.25, 0.4), ((2, 3), (10, 10), (2, 4)), 0,
        p95_cost=(13.0, 2.5, 0.03),
    )  # fmt: skip

    row = ablation_table([("v0.yaml", old), ("v0.yaml", second), ("v0.yaml", third)])

    # p95 latency (10.0 + 13.0) / 2 = 11.5; retrieve p95 2.5 from the third run alone, so no
    # range; cost (0.02 + 0.03) / 2 = 0.025. The existing cells are unchanged.
    assert row.splitlines()[4] == (
        "| dense | v0.yaml 01234567 | 3 | 40 | 0.500 (0.500–0.500) | 1.000 (1.000–1.000) "
        "| 0.250 (0.250–0.250) | 0.400 (0.400–0.400) | 0.667 (0.667–0.667) "
        "| 1.000 (1.000–1.000) | 0.500 (0.500–0.500) | 0.000 (0.000–0.000) "
        "| 11.5 (10.0–13.0) | 2.5 | 0.0250 (0.0200–0.0300) | n/a | n/a | n/a | n/a |"
    )


def test_time_cells_are_each_runs_count_over_total_and_leave_out_a_run_without_them() -> None:
    # S09-T3. Three runs of one row: the first written before S09-T3 (no time counts), the second
    # with no routes (not temporal mode), the third with all 3. Old runs' cells are unchanged.
    metrics, ac = (0.5, 1.0, 0.25, 0.4), ((2, 3), (10, 10), (2, 4))
    old = _summary(SHA_V0, 9, 40, metrics, ac, 0)
    second = _summary(
        SHA_V0, 10, 40, metrics, ac, 0,
        time=(Count(count=39, total=100), Rate(pass_=31, total=90), None),
    )  # fmt: skip
    third = _summary(
        SHA_V0, 11, 40, metrics, ac, 0,
        time=(Count(count=38, total=100), Rate(pass_=32, total=90), Rate(pass_=35, total=36)),
    )  # fmt: skip

    row = ablation_table([("v0.yaml", old), ("v0.yaml", second), ("v0.yaml", third)])

    # Stale: 39/100 = 0.390 and 38/100 = 0.380, mean 0.385. Temporal: 31/90 = 0.34444 and 32/90
    # = 0.35556, mean 0.35000. Router: the third run's 35/36 = 0.97222 alone, so no range. No
    # authority selection (before S09-T7).
    assert row.splitlines()[4].endswith(
        "| n/a | n/a | n/a | 0.385 (0.380–0.390) | 0.350 (0.344–0.356) | 0.972 | n/a |"
    )


def test_a_time_count_with_no_total_is_n_a() -> None:
    # A count over 0 hits has no rate, as an AC with total 0.
    empty = (Count(count=0, total=0), Rate(pass_=0, total=0), Rate(pass_=0, total=0))
    run = _summary(
        SHA_V0, 9, 40, (0.5, 1.0, 0.25, 0.4), ((2, 3), (10, 10), (2, 4)), 0,
        p95_cost=(10.0, 2.5, 0.02), time=empty,
    )  # fmt: skip

    row = ablation_table([("v0.yaml", run)]).splitlines()[4]

    assert row.endswith("| 10.0 | 2.5 | 0.0200 | n/a | n/a | n/a | n/a |")


def test_the_authority_cell_is_each_runs_rate_after_router_and_older_rows_say_n_a() -> None:
    # S09-T7. One row of 3 runs: the first written before S09-T7 (no authority), then 9 of 9 and
    # 8 of 9. A second row written before S09-T7 keeps every cell, with n/a in the new one.
    metrics, ac = (0.5, 1.0, 0.25, 0.4), ((2, 3), (10, 10), (2, 4))
    old = _summary(SHA_V0, 9, 40, metrics, ac, 0, "authority")
    second = _summary(SHA_V0, 10, 40, metrics, ac, 0, "authority", authority=Rate(pass_=9, total=9))
    third = _summary(SHA_V0, 11, 40, metrics, ac, 0, "authority", authority=Rate(pass_=8, total=9))

    lines = ablation_table(
        [("v0.yaml", old), ("v0.yaml", second), ("v0.yaml", third), ("v0.yaml", V0_FIRST)]
    ).splitlines()

    # 9/9 = 1.000 and 8/9 = 0.889, mean 0.94444. The authority row's first run (9:00) is before
    # V0_FIRST (10:00), so it comes first.
    assert lines[4].endswith("| n/a | n/a | n/a | 0.944 (0.889–1.000) |")
    assert lines[5] == (
        "| dense | v0.yaml 01234567 | 1 | 40 | 0.500 | 1.000 | 0.250 | 0.400 | 0.667 | 1.000 "
        "| 0.500 | 0.000 | n/a | n/a | n/a | n/a | n/a | n/a | n/a |"
    )


def test_no_runs_is_a_table_with_no_rows() -> None:
    assert ablation_table([]) == GENERATED + "\n" + HEADER
