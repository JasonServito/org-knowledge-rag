"""The ablation table (S06-T4): one row per pipeline and golden set, rebuilt from every results
folder, so it never needs editing by hand.

A row is a (name, golden_sha256) pair, in order of its first run. Each value is the mean over
the row's runs to 3 decimals, then its range, min and max joined by an en dash, when more than
one run has it; an AC cell is the mean of each run's pass rate. A folder without `summary.json`
(such as `s04/`) is skipped.
"""

from collections.abc import Sequence
from pathlib import Path

from orgknow.eval.runner import Rate, RunInfo, Summary

GENERATED = (
    "Generated by `make eval-table` from each results folder's run.json and summary.json: "
    "don't edit."
)
COLUMNS = [
    *("Pipeline", "Set", "Runs", "Questions", "Recall@10", "Hit@10", "MRR", "nDCG@10"),
    *("AC1", "AC2", "AC3", "Errors"),
]


def load_runs(results_dir: Path) -> list[tuple[str, Summary]]:
    """Each run folder's golden file name (from `run.json`) and summary."""
    runs = []
    for summary_path in sorted(results_dir.glob("*/summary.json")):
        run_json = (summary_path.parent / "run.json").read_text(encoding="utf-8")
        golden_name = Path(RunInfo.model_validate_json(run_json).golden_path).name
        summary = Summary.model_validate_json(summary_path.read_text(encoding="utf-8"))
        runs.append((golden_name, summary))
    return runs


def ablation_table(runs: Sequence[tuple[str, Summary]]) -> str:
    """The table in Markdown, from (golden file name, summary) pairs in any order."""
    rows: dict[tuple[str, str], list[tuple[str, Summary]]] = {}  # a dict keeps insertion order
    for run in sorted(runs, key=lambda run: run[1].started_at):
        rows.setdefault((run[1].name, run[1].golden_sha256), []).append(run)

    lines = [GENERATED, "", _line(COLUMNS), "|" + "---|" * len(COLUMNS)]
    for (name, golden_sha256), row in rows.items():
        summaries = [summary for _, summary in row]
        lines.append(
            _line(
                [
                    name,
                    f"{row[0][0]} {golden_sha256[:8]}",
                    str(len(summaries)),
                    ", ".join(str(n) for n in sorted({s.questions for s in summaries})),
                    _cell([s.recall for s in summaries]),
                    _cell([s.hit for s in summaries]),
                    _cell([s.mrr for s in summaries]),
                    _cell([s.ndcg for s in summaries]),
                    _cell([_pass_rate(s.ac1) for s in summaries]),
                    _cell([_pass_rate(s.ac2) for s in summaries]),
                    _cell([_pass_rate(s.ac3) for s in summaries]),
                    _cell([float(s.errors) for s in summaries]),
                ]
            )
        )
    return "\n".join(lines) + "\n"


def write_table(results_dir: Path) -> Path:
    """Rebuild `<results_dir>/ablation.md` from every run folder in it; return its path."""
    path = results_dir / "ablation.md"
    results_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(ablation_table(load_runs(results_dir)), encoding="utf-8")
    return path


def _cell(values: Sequence[float | None]) -> str:
    """The mean of the values that aren't None, with their range when there are several."""
    known = [value for value in values if value is not None]
    if not known:
        return "n/a"
    cell = f"{sum(known) / len(known):.3f}"
    if len(known) > 1:
        cell += f" ({min(known):.3f}\N{EN DASH}{max(known):.3f})"
    return cell


def _pass_rate(rate: Rate) -> float | None:
    return rate.pass_ / rate.total if rate.total else None


def _line(cells: Sequence[str]) -> str:
    return "| " + " | ".join(cells) + " |"
