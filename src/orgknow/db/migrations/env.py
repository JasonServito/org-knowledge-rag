"""Alembic environment: applies migrations to the database in Settings().database_url.

SQLAlchemy is used here only because Alembic requires it; the app's data-access approach is
decided separately (ADR-005).
"""

import logging

from alembic import context
from sqlalchemy import create_engine, pool

from orgknow.db.url import with_psycopg_driver
from orgknow.settings import Settings

# Show Alembic's progress lines ("Running upgrade ...") and only warnings from everything else.
logging.basicConfig(format="%(levelname)-5.5s [%(name)s] %(message)s")
logging.getLogger("alembic").setLevel(logging.INFO)


def run_migrations_online() -> None:
    # NullPool: a migration run is one short-lived process, so pooling connections buys nothing.
    engine = create_engine(with_psycopg_driver(Settings().database_url), poolclass=pool.NullPool)
    with engine.connect() as connection:
        # No target_metadata: migrations are hand-written, not autogenerated from models.
        context.configure(connection=connection, target_metadata=None)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    raise SystemExit("Offline (--sql) mode is not supported; run migrations against a database.")
run_migrations_online()
